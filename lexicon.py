# ---------- 比對函式 ----------
def _negated(text: str, start: int) -> bool:
    """情緒詞前面是否有否定詞（中間允許夾程度副詞）"""
    prefix = text[max(0, start - 6):start]
    changed = True
    while changed:  # 從尾巴一路剝掉程度副詞
        changed = False
        for w in sorted(INTENSIFIERS, key=len, reverse=True):
            if prefix.endswith(w):
                prefix = prefix[: -len(w)]
                changed = True
    return any(prefix.endswith(n) for n in NEGATORS)


def sentiment_score(text: str):
    """回傳 (分數, 命中的詞)；分數 > 0 正面、< 0 負面、= 0 中性或無法判斷"""
    text = str(text)
    for w in NEUTRAL_MASK:
        text = text.replace(w, "□" * len(w))
    lexicon = [(w, 1) for w in POSITIVE] + [(w, -1) for w in NEGATIVE]
    lexicon.sort(key=lambda x: len(x[0]), reverse=True)  # 長詞優先

    score, hits = 0, []
    for word, polarity in lexicon:
        start = text.find(word)
        while start != -1:
            # 否定詞本身已經寫進詞彙的（例如「不好喝」）就不再反轉
            p = polarity
            if not word.startswith(("不", "沒")) and _negated(text, start):
                p = -p
            score += p
            hits.append(word if p == polarity else f"(否定){word}")
            # 用符號蓋掉已比對的字，避免「不好喝」裡的「好喝」再被算一次
            text = text[:start] + "□" * len(word) + text[start + len(word):]
            start = text.find(word, start + len(word))
    return score, hits


def find_topics(text: str):
    text = str(text)
    return [t for t, words in TOPICS.items() if any(w in text for w in words)]